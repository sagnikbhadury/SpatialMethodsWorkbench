engine_features <- c("epithelial", "APC", "CTL", "Treg", "T_helper")
smoke_settings <- list(rank = 2L, anchor_min = 12L, anchor_max = 24L, gp_neighbors = 5L,
                       gp_maxit = 3L, factor_maxit = 60L, threads = 1L, seed = 7L, threshold = .05)

test_that("ISPAT3D-backed paths are gated on zone sizes and the installed engine", {
  volume <- demo_spatial_3d_data(72, volumes = 2, seed = 2026)
  mapping <- list(x = "x", y = "y", z = "z", zone = "zone", id = "volume_id")
  registry <- analysis_registry()
  expect_identical(registry$ispat$package, "ISPAT3D")
  expect_identical(registry$ispat3d$package, "ISPAT3D")
  too_many <- method_compatibility(registry$ispat3d, volume[1:14, ], mapping, engine_features)
  expect_false(too_many$compatible)
  expect_match(too_many$reason, "more complete rows than selected features", fixed = TRUE)
  one_zone <- volume; one_zone$zone <- "Only"
  single <- method_compatibility(registry$ispat, one_zone, mapping, engine_features)
  expect_false(single$compatible)
  expect_match(single$reason, "at least two zones", fixed = TRUE)
})

test_that("section identifiers are only used when they look like section labels", {
  spatial <- demo_spatial_data(72)
  pooled <- engine_sections(spatial, list(id = "sample_id"), list())
  expect_equal(pooled$count, 1L)
  expect_match(pooled$note, "not treated as a section identifier", fixed = TRUE)
  volume <- demo_spatial_3d_data(72, volumes = 2, seed = 2026)
  used <- engine_sections(volume, list(id = "volume_id"), list())
  expect_equal(used$count, 2L)
  forced <- engine_sections(volume, list(id = "volume_id"), list(use_sections = "none"))
  expect_equal(forced$count, 1L)
  expect_equal(engine_sections(volume, list(), list())$count, 1L)
})

test_that("ISPAT3D planar fit powers the ISPat 2D path", {
  skip_if_not_installed("ISPAT3D", "0.3.0")
  skip_if_not_installed("gpboost")
  data <- demo_spatial_data(90, seed = 11)
  mapping <- list(x = "x", y = "y", zone = "zone", id = "sample_id")
  result <- run_analysis("ispat", data, mapping, engine_features, smoke_settings)
  expect_identical(result$engine$package, "ISPAT3D")
  expect_identical(result$engine$call, "ISPAT3D::ispat3d_fit_2d")
  expect_true(all(names(result$matrices) %in% unique(as.character(data$zone))))
  expect_false("Shared" %in% names(result$matrices))
  expect_true(all(abs(diag(result$matrices[[1]]) - 1) < 1e-8))
  expect_equal(unname(result$summary["zones"]), length(unique(data$zone)))
  expect_true(is.data.frame(result$gp_log))
  expect_s3_class(result$plot, "ggplot")
  expect_true(all(c("network", "source", "target", "weight", "sign") %in% names(result$table)))
  expect_true(any(grepl("one section", result$notes, fixed = TRUE)))
  manifest <- result_manifest(result)
  expect_identical(manifest$engine$package, "ISPAT3D")
})

test_that("ISPAT3D volumetric fit powers the ISPat 3D path", {
  skip_if_not_installed("ISPAT3D", "0.3.0")
  skip_if_not_installed("gpboost")
  volume <- demo_spatial_3d_data(72, volumes = 2, seed = 2026)
  mapping <- list(x = "x", y = "y", z = "z", zone = "zone", id = "volume_id")
