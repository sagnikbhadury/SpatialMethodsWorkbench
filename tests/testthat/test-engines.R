  expect_identical(result$engine$call, "ISPAT3D::ispat3d_fit")
  expect_equal(length(result$matrices), 3L)
  expect_true(any(grepl("identified 2 sections", result$notes, fixed = TRUE)))
  expect_equal(unname(result$summary["gp_fits"]), 3L * length(engine_features))
  expect_true(all(is.finite(result$matrices[["High"]])))
  expect_s3_class(result$plot, "ggplot")
  expect_equal(result$matrices[["High"]], result$raw$partial[["High"]], ignore_attr = TRUE)
})

test_that("GPGHS 1.0 selection rule and edge table are used", {
  skip_if_not_installed("GPGHS", "1.0.0")
  data <- demo_spatial_data(80, seed = 5)
  result <- run_analysis("gpghs", data, list(x = "x", y = "y"), engine_features,
                         list(basis = 2L, nmc = 300L, burn = 100L, thin = 2L, cores = 1L, seed = 3L))
  expect_identical(result$engine$package, "GPGHS")
  expect_equal(unname(result$summary["edge_threshold"]), .5)
  expect_equal(unname(result$summary["retained_draws"]), 100)
  expect_equal(result$raw$settings$edge_threshold, .5)
  expect_equal(result$raw$settings$symmetry, "AND")
  expect_true(all(c("score", "sign", "sign_change", "kappa_from_to") %in% names(result$table)))
  expect_equal(nrow(result$table), sum(result$raw$adj[upper.tri(result$raw$adj)]))
  expect_true(all(result$table$weight >= 0))
  expect_s3_class(result$plot, "ggplot")
  strict <- run_analysis("gpghs", data, list(x = "x", y = "y"), engine_features,
                         list(basis = 2L, nmc = 300L, burn = 100L, thin = 2L, cores = 1L, seed = 3L, edge_threshold = .2))
  expect_lte(nrow(strict$table), nrow(result$table))
})
